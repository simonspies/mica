(* TEST: roundtrip *)
open Mica

let _ = assert (Int32.equal Int32.zero 0l)
let _ = assert (Int32.equal Int32.one 1l)
let _ = assert (Int32.equal Int32.minus_one (-1l))
let _ = assert (Int32.equal Int32.min_int (-2147483648l))
let _ = assert (Int32.equal Int32.max_int 2147483647l)

let _ = assert (Int32.equal (Int32.neg 5l) (-5l))
let _ = assert (Int32.equal (Int32.lognot 0l) (-1l))
let _ = assert (Int32.equal (Int32.add 2147483647l 1l) (-2147483648l))
let _ = assert (Int32.equal (Int32.sub 3l 5l) (-2l))
let _ = assert (Int32.equal (Int32.mul 7l 6l) 42l)
let _ = assert (Int32.equal (Int32.div (-7l) 3l) (-2l))
let _ = assert (Int32.equal (Int32.unsigned_div (-1l) 2l) 2147483647l)
let _ = assert (Int32.equal (Int32.rem (-7l) 3l) (-1l))
let _ = assert (Int32.equal (Int32.unsigned_rem (-1l) 3l) 0l)
let _ = assert (Int32.equal (Int32.logand 0x55l 0x0fl) 0x05l)
let _ = assert (Int32.equal (Int32.logor 0x50l 0x0fl) 0x5fl)
let _ = assert (Int32.equal (Int32.logxor 0x55l 0x0fl) 0x5al)
let _ = assert (Int32.equal (Int32.min (-4l) 3l) (-4l))
let _ = assert (Int32.equal (Int32.max (-4l) 3l) 3l)
let _ = assert (Int32.compare (-4l) 3l = -1)
let _ = assert (Int32.compare 3l 3l = 0)
let _ = assert (Int32.compare 4l 3l = 1)
let _ = assert (Int32.unsigned_compare (-1l) 0l = 1)
let _ = assert (Int32.equal (Int32.shift_left 1l 31) (-2147483648l))
let _ = assert (Int32.equal (Int32.shift_right (-8l) 2) (-2l))
let _ = assert (Int32.equal (Int32.shift_right_logical (-1l) 1) 2147483647l)
let _ = assert (Int32.equal (Int32.of_int (-7)) (-7l))
let _ = assert (Int32.to_int (-7l) = -7)

let _ = assert (Int64.equal Int64.zero 0L)
let _ = assert (Int64.equal Int64.one 1L)
let _ = assert (Int64.equal Int64.minus_one (-1L))
let _ = assert (Int64.equal Int64.min_int (-9223372036854775808L))
let _ = assert (Int64.equal Int64.max_int 9223372036854775807L)

let _ = assert (Int64.equal (Int64.neg 5L) (-5L))
let _ = assert (Int64.equal (Int64.lognot 0L) (-1L))
let _ = assert (Int64.equal (Int64.add 9223372036854775807L 1L) (-9223372036854775808L))
let _ = assert (Int64.equal (Int64.sub 3L 5L) (-2L))
let _ = assert (Int64.equal (Int64.mul 7L 6L) 42L)
let _ = assert (Int64.equal (Int64.div (-7L) 3L) (-2L))
let _ = assert (Int64.equal (Int64.unsigned_div (-1L) 2L) 9223372036854775807L)
let _ = assert (Int64.equal (Int64.rem (-7L) 3L) (-1L))
let _ = assert (Int64.equal (Int64.unsigned_rem (-1L) 3L) 0L)
let _ = assert (Int64.equal (Int64.logand 0x55L 0x0fL) 0x05L)
let _ = assert (Int64.equal (Int64.logor 0x50L 0x0fL) 0x5fL)
let _ = assert (Int64.equal (Int64.logxor 0x55L 0x0fL) 0x5aL)
let _ = assert (Int64.equal (Int64.min (-4L) 3L) (-4L))
let _ = assert (Int64.equal (Int64.max (-4L) 3L) 3L)
let _ = assert (Int64.compare (-4L) 3L = -1)
let _ = assert (Int64.compare 3L 3L = 0)
let _ = assert (Int64.compare 4L 3L = 1)
let _ = assert (Int64.unsigned_compare (-1L) 0L = 1)
let _ = assert (Int64.equal (Int64.shift_left 1L 63) (-9223372036854775808L))
let _ = assert (Int64.equal (Int64.shift_right (-8L) 2) (-2L))
let _ = assert (Int64.equal (Int64.shift_right_logical (-1L) 1) 9223372036854775807L)
let _ = assert (Int64.equal (Int64.of_int (-7)) (-7L))
let _ = assert (Int64.to_int (-7L) = -7)
let _ = assert (Int64.to_int Int64.max_int = -1)
let _ = assert (Int64.to_int Int64.min_int = 0)
let _ = assert (Int64.equal (Int64.of_int32 (-1l)) (-1L))
let _ = assert (Int32.equal (Int64.to_int32 0x1_0000_0001L) 1l)

let _ = assert (Int32.equal 0b1010_0101l 0xa5l)
let _ = assert (Int32.equal 0o377l 255l)
let _ = assert (Int64.equal 0xffff_ffff_ffff_ffffL (-1L))
